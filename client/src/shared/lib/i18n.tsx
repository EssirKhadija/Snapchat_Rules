interface I18nContextValue {
  locale: Locale;
  toggleLocale: () => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

export const I18nProvider = ({ children }: { children: ReactNode }) => {
  const [locale, setLocale] = useState<Locale>('fr');

  useEffect(() => {
    const savedLocale = localStorage.getItem('locale') as Locale | null;
    if (savedLocale === 'fr' || savedLocale === 'en') {
      setLocale(savedLocale);
    }
  }, []);

  useEffect(() => {
    localStorage.setItem('locale', locale);
  }, [locale]);

  const toggleLocale = () => {
    setLocale(current => (current === 'fr' ? 'en' : 'fr'));
  };

  const t = useMemo(
    () => (key: string, vars?: Record<string, string | number>) => {
      let value = translations[locale]?.[key] ?? key;
      if (vars) {
        Object.entries(vars).forEach(([varKey, varValue]) => {
          value = value.replace(new RegExp(`\\{\\{${varKey}\\}\\}`, 'g'), String(varValue));
        });
      }
      return value;
    },
    [locale]
  );

  return <I18nContext.Provider value={{ locale, toggleLocale, t }}>{children}</I18nContext.Provider>;
};

export const useTranslation = () => {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useTranslation must be used within I18nProvider');
  }
  return context;
};
